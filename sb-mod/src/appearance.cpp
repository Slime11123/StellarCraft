// StellarCraft — appearance consumer (Stellar Blade side).
//
// Reads the MC player's skin + cape from the shared-memory appearance region and applies
// them to the in-world character that represents the Minecraft player (Steve).
//
// The MC side (dev.stellarcraft.client.AppearanceBridge) writes RGBA8 pixels + a seqlock
// header. Here we:
//   1. Detect a change via the header's seq (or skinHash/capeHash).
//   2. Copy the pixels out (the header commit guarantees they are stable enough; a torn
//      read self-heals next frame).
//   3. Upload to Unreal via a dynamic UTexture2D and set it on the character's material.
//
// This file is a SKELETON following the same pattern as the rest of the mod: real Unreal
// calls are commented where they require the dumped SDK headers.

