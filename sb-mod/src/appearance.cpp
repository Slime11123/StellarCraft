        // // Skin: create/update a UTexture2D of hdr->skinW x hdr->skinH (RGBA8, sRGB)
        // // and set it as the "skin" material parameter on the character's mesh.
        // // Cape: same for hdr->capeW x hdr->capeH, only if hasCape.
        //
        // if (hasSkin) upload_texture(skinPixels, hdr->skinW, hdr->skinH, /*srgb=*/true,  skinSlot);
        // if (hasCape) upload_texture(capePixels, hdr->capeW, hdr->capeH, /*srgb=*/true,  capeSlot);
        //
        // // Slim vs default arm model toggles which mesh/skeleton is used.
