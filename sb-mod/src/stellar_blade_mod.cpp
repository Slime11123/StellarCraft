// This is the counterpart to the Minecraft Fabric mod. It runs INSIDE Stellar Blade
// (UE4.26) via UE4SS's C++ Modding API, and is responsible for the "world" half:
//
//   * Reading the player character's transform and the nearby world geometry.
//   * Exporting collision shapes (from Unreal's collision) to Minecraft.
//   * Mirroring nearby NPCs/enemies as hittable actor proxies.
//   * Forwarding raw keyboard/mouse input to Minecraft.
//   * Compositing Minecraft's overlay (blocks/hand/GUI) into Stellar Blade's frame.
