    // -----------------------------------------------------------------------------------
    // Shared-memory handle + mapped views. Created once at startup.
    // These are the single definition; other modules access them via shared.h (extern).
    // -----------------------------------------------------------------------------------
    HANDLE  g_hMapping = nullptr;
    uint8_t* g_pBase   = nullptr;

    static bool create_mapping()
    {
        g_hMapping = CreateFileMappingW(INVALID_HANDLE_VALUE, nullptr, PAGE_READWRITE,
                                        (DWORD)(kMappingBytes >> 32),
                                        (DWORD)(kMappingBytes & 0xFFFFFFFF),
                                        kMappingName);
        if (!g_hMapping) return false;

        g_pBase = (uint8_t*)MapViewOfFile(g_hMapping, FILE_MAP_ALL_ACCESS, 0, 0, kMappingBytes);
        if (!g_pBase) { CloseHandle(g_hMapping); g_hMapping = nullptr; return false; }

        // Init header.
        auto* hdr = reinterpret_cast<Header*>(g_pBase + kOffHeader);
        hdr->magic = kMagic;
        hdr->version = kVersion;
        hdr->sbPid = GetCurrentProcessId();
        hdr->mcPid = 0;
        hdr->sbHeartbeatMs = 0;
        hdr->mcHeartbeatMs = 0;

        // Zero the rest (protocol expects clean rings/seqlocks).
        std::memset(g_pBase + kOffHeader + sizeof(Header), 0,
                    kMappingBytes - kOffHeader - sizeof(Header));
        return true;
    }

    // -----------------------------------------------------------------------------------
    // Player transform: read the local player character's location/rotation from Unreal.
    // (PlayerSnapshot is declared in shared.h, shared with the collision exporter.)
    // -----------------------------------------------------------------------------------

    // Real impl: get the local player character from Unreal's world, read its
    // K2_GetActorLocation / GetControlRotation, convert Unreal(cm, Z-up) to MC(block, Y-up).
    //
    // SDK (real, dumped from Stellar Blade):
    //   ACH_P_EVE_01_Blueprint_C : ASBCharacter : ACharacter
    //   -> so K2_GetActorLocation() / GetControlRotation() / FollowCamera are all valid.
    // See docs/SDK_MAPPING.md for the full mapping.
    static PlayerSnapshot read_player()
    {
        PlayerSnapshot s{};
        s.inGame = false;

        // Uncomment once building against the real SDK:
        // #include <SDK/CH_P_EVE_01_Blueprint_classes.hpp>
        // #include <SDK/Engine_classes.hpp>
        //
        // auto* World = UObject::GWorld;
        // if (!World) return s;
        // auto* PC = World->GetFirstPlayerController();
        // if (!PC || !PC->GetCharacter()) return s;
        // auto* PlayerChar = static_cast<ACH_P_EVE_01_Blueprint_C*>(PC->GetCharacter());
        //
        // FVector loc = PlayerChar->K2_GetActorLocation();   // cm, Z-up
        // FRotator rot = PlayerChar->GetControlRotation();   // degrees
        //
        // // Unreal (cm, Z-up) -> MC (block, Y-up)
        // // Axis swap: Unreal Z(up) -> MC Y(up); Unreal X -> MC X; Unreal Y -> MC Z.
        // s.x =  loc.X / kUnitsPerBlock;
        // s.y =  loc.Z / kUnitsPerBlock;   // Z-up becomes MC Y-up
        // s.z = -loc.Y / kUnitsPerBlock;   // negate to preserve handedness
        // s.yaw   = -rot.Yaw;
        // s.pitch = rot.Pitch;
        // s.inGame = true;
        return s;
    }

    // -----------------------------------------------------------------------------------
    // Per-frame update. Called from a UE4SS tick hook (e.g. a registered Lua/C++ tick,
    // or a hook on the game's frame loop).
    // -----------------------------------------------------------------------------------
    static void on_frame()
    {
        if (!g_pBase) return;

        // 1. Heartbeat.
        auto* hdr = reinterpret_cast<Header*>(g_pBase + kOffHeader);
        hdr->sbHeartbeatMs = GetTickCount64();

        // 2. Write SB state (seqlock).
        PlayerSnapshot ps = read_player();

        auto* sbState = reinterpret_cast<SbState*>(g_pBase + kOffSbState);
        uint32_t seq = sbState->seq + 1;
        sbState->seq = seq | 1;              // begin write (odd)

        sbState->flags = ps.inGame ? kSbInGame : 0;
        // sbState->levelId = ...;           // hash of current level name
        sbState->posX = ps.x;
        sbState->posY = ps.y;
        sbState->posZ = ps.z;
        sbState->yaw = ps.yaw;
        sbState->pitch = ps.pitch;

        sbState->seq = seq + 1;              // end write (even)

        // 3. Export collision (see collision_exporter.cpp) and actors (actor_mirror.cpp),
        //    forward input (input_bridge.cpp), and composite MC overlay (overlay.cpp).
        //    Each is a separate module called here.

        // 4. Apply the MC player's skin/cape to the Steve proxy (appearance.cpp).
        update_appearance();
    }

