// StellarCraft — collision exporter (Stellar Blade side).
//
// Turns Stellar Blade's world geometry into the AABBs Minecraft needs to walk on it.
// This is the SB-side counterpart of dev.stellarcraft.world.CollisionField.
//
// Two-stage approach (mirroring SkyCraft's design):
//
//   Stage A (MVP):  sweep the area around the player with Unreal line/capsule traces on a
//                   grid, and emit one AABB per "solid" cell. Cheap, covers terrain and
//                   most statics, but misses thin geometry (fences, railings).
//
//   Stage C (final): walk the loaded UWorld, read the actual collision primitives (boxes,
//                   capsules, convex hulls, landscape heightfields) from each primitive
//                   component, voxelize them into AABBs. Exact, but requires decoding
//                   Unreal's physics shapes.
//
// Each section (16-block cube) streams as a kColSection delta into the collision ring.
//
// NOTE: This file is a skeleton. The real implementation needs the Unreal/UE4SS SDK
// headers (generated by the UHT dumper) and concrete class/offset info.

