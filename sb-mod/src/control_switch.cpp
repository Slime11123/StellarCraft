    // Switch control. Called when F4 is detected.
    static void switch_control()
    {
        if (g_control == Control::EVELYN) {
            g_control = Control::STEVE;
            set_eve_controlled(false);       // Eve goes passive
            set_sb_hud_visible(false);       // MC HUD takes over
            publish_control_bit(true);       // tell MC to unfreeze + grab input
        } else {
            g_control = Control::EVELYN;
            set_eve_controlled(true);
            set_sb_hud_visible(true);
            publish_control_bit(false);      // tell MC to freeze + drop input
        }
    }

    // Called each frame to poll the hotkey.
    static void poll_hotkey()
    {
        bool f4 = (GetAsyncKeyState(VK_F4) & 0x8000) != 0;
        if (f4 && !g_f4WasDown) {
            switch_control();
        }
        g_f4WasDown = f4;
    }

